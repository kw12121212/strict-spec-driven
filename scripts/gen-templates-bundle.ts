#!/usr/bin/env bun
// Reads all files under templates/ and generates src/embedded-templates.ts
import { readdirSync, readFileSync, statSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.dirname(SCRIPT_DIR);
const TEMPLATES_DIR = path.join(ROOT, "templates");
const OUTPUT_FILE = path.join(ROOT, "src", "embedded-templates.ts");

function collectFiles(dir: string): string[] {
  const result: string[] = [];
  for (const entry of readdirSync(dir).sort()) {
    const full = path.join(dir, entry);
    if (statSync(full).isDirectory()) {
      result.push(...collectFiles(full));
    } else {
      result.push(full);
    }
  }
  return result;
}

const files = collectFiles(TEMPLATES_DIR);
const entries: string[] = [];

for (const file of files) {
  const key = path.relative(TEMPLATES_DIR, file).replace(/\\/g, "/");
  const content = readFileSync(file, "utf8");
  const escaped = content.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  entries.push(`  ${JSON.stringify(key)}: \`${escaped}\``);
}

const output = `// Auto-generated by scripts/gen-templates-bundle.ts — do not edit manually
export const EMBEDDED_TEMPLATES: Record<string, string> = {
${entries.join(",\n")},
};

export function hasEmbeddedTemplate(key: string): boolean {
  return key in EMBEDDED_TEMPLATES;
}

export function readEmbeddedTemplate(key: string): string | undefined {
  return EMBEDDED_TEMPLATES[key];
}
`;

writeFileSync(OUTPUT_FILE, output, "utf8");
console.log(`Generated src/embedded-templates.ts with ${files.length} template files`);
