#!/usr/bin/env bun
// Reads bundled strict assets and generates src/embedded-templates.ts
import { readdirSync, readFileSync, statSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.dirname(SCRIPT_DIR);
// `templates` keys drop their root segment; every other root keeps it, so the embedded key matches
// the repository-relative path that schema-show, sample-show, and the mutation surface already use.
const ASSET_ROOTS = ["templates", "examples", "inventory"] as const;
const OUTPUT_FILE = path.join(ROOT, "src", "embedded-templates.ts");

function collectFiles(dir: string): string[] {
  const result: string[] = [];
  for (const entry of readdirSync(dir).sort()) {
    const full = path.join(dir, entry);
    if (statSync(full).isDirectory()) {
      result.push(...collectFiles(full));
    } else {
      result.push(full);
    }
  }
  return result;
}

const entries: string[] = [];

let fileCount = 0;
for (const assetRoot of ASSET_ROOTS) {
  const assetRootDir = path.join(ROOT, assetRoot);
  const files = collectFiles(assetRootDir);
  fileCount += files.length;
  for (const file of files) {
    const relativePath = path.relative(assetRootDir, file);
    const key = (assetRoot === "templates" ? relativePath : path.join(assetRoot, relativePath)).replace(/\\/g, "/");
    const content = readFileSync(file, "utf8");
    const escaped = content.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
    entries.push(`  ${JSON.stringify(key)}: \`${escaped}\``);
  }
}

const output = `// Auto-generated by scripts/gen-templates-bundle.ts — do not edit manually
export const EMBEDDED_TEMPLATES: Record<string, string> = {
${entries.join(",\n")},
};

export function hasEmbeddedTemplate(key: string): boolean {
  return key in EMBEDDED_TEMPLATES;
}

export function getEmbeddedTemplateKeys(): string[] {
  return Object.keys(EMBEDDED_TEMPLATES).sort();
}

export function readEmbeddedTemplate(key: string): string | undefined {
  return EMBEDDED_TEMPLATES[key];
}
`;

writeFileSync(OUTPUT_FILE, output, "utf8");
console.log(`Generated src/embedded-templates.ts with ${fileCount} bundled asset files`);
